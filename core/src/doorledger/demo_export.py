"""The messages the hosted demo shows, generated from the backend so the two never drift.

``demo_messages()`` replays the ``full_day`` scenario offline (template writer, console
notifier, no call placed) and returns every action the rules took. The dashboard's mock mode
reads the result from ``web/dashboard/lib/mock/messages.json``; regenerate it with

    uv run --package doorledger python scripts/export_mock_messages.py

``core/tests/test_wording.py`` fails if the committed file is out of date.
"""

from __future__ import annotations

import json
from datetime import datetime
from pathlib import Path
from typing import Any
from zoneinfo import ZoneInfo

ROOT = Path(__file__).resolve().parents[3]
MOCK_MESSAGES = ROOT / "web" / "dashboard" / "lib" / "mock" / "messages.json"
DEMO_DAY = datetime(2026, 1, 13)  # any day: only local times are exported


def demo_messages() -> dict[str, Any]:
    from .agent import replay_scenario
    from .clock import SimClock
    from .domain import utcnow
    from .engine import Engine
    from .household import demo_household
    from .ledger import Ledger
    from .notify import ConsoleNotifier
    from .responder import Responder, TemplateWriter
    from .weather import AmbientTemperature

    hh = demo_household()
    tz = ZoneInfo(hh.patient.timezone)
    engine = Engine(hh, Ledger(household=hh.id), Responder(hh, ConsoleNotifier(), TemplateWriter()),
                    SimClock(utcnow(), 0.0), AmbientTemperature(hh.lat, hh.lon, override_c=-9.0))
    replay_scenario(engine, "full_day", DEMO_DAY.replace(tzinfo=tz))
    findings = {r["id"]: r["body"] for r in engine.ledger.records(kinds=["finding"])}
    actions = []
    for r in engine.ledger.records(kinds=["action"]):
        a = r["body"]
        f = findings.get(a.get("finding_id") or "", {})
        d = a["data"]
        row = {
            "at": datetime.fromisoformat(a["at"]).astimezone(tz).strftime("%H:%M"),
            "kind": a["kind"],
            "role": d.get("role"),
            "finding": f"{f.get('kind')}/{f.get('severity')}" if f else None,
            "purpose": d.get("purpose"),
            "channel": d.get("channel"),
            "language": d.get("language"),
            "message": a["message"],
        }
        for k in ("status", "attempt", "ssml"):
            if k in d:
                row[k] = d[k]
        actions.append(row)
    return {
        "_note": "Generated by scripts/export_mock_messages.py from the backend templates "
                 "(full_day replay). Do not edit by hand.",
        "actions": actions,
    }


def render() -> str:
    return json.dumps(demo_messages(), ensure_ascii=False, indent=2) + "\n"
