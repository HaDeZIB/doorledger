"""Fixed wording for the two people an LLM never writes to: the patient and the neighbor.

Rosa is 81, speaks Spanish, uses no apps and may hear, see or remember less than she used to
(docs/reviews/improvements-04.md, geriatric-care review). So everything she receives follows
the same rules, every time:

* the same opening and sender: "Hola, señora Rosa. Le llamamos de parte de su hija Ana.";
* short sentences, one action, a safe way out, and no links or numbers to interpret;
* never asks her to go out onto ice ("Si hay hielo en el escalón, no salga sola");
* never asks her to reply: Ring seeing the box picked up is her answer;
* the call says the key sentence twice, slowly (SSML ``prosody rate="88%"`` with short breaks).

The neighbor gets the least health information needed: "a delivery that must not stay out in
the cold", never what is in the box.

The dashboard's hosted demo shows these exact strings (web/dashboard/lib/mock/messages.json,
generated by scripts/export_mock_messages.py and checked by tests/test_wording.py).
"""

from __future__ import annotations

from dataclasses import dataclass
from xml.sax.saxutils import escape

from .household import Household

BREAK = "<break>"  # a short pause in a call script
PAUSE = "<pause>"  # a longer one, before the key sentence is repeated
SPEECH_RATE = "88%"

_RELATION_ES = {"daughter": "su hija", "son": "su hijo", "granddaughter": "su nieta",
                "grandson": "su nieto", "niece": "su sobrina", "nephew": "su sobrino"}


@dataclass(frozen=True)
class Call:
    """A call script: ``text`` is shown on the dashboard, ``ssml`` is what the voice says."""

    text: str
    ssml: str


@dataclass(frozen=True)
class People:
    """First names (and the family member's relation) the fixed wording needs."""

    patient: str
    family: str | None
    relation: str | None  # "daughter", from "Ana Martínez (daughter)"
    neighbor: str | None

    @classmethod
    def of(cls, household: Household) -> People:
        family = next(iter(household.by_role("family")), None)
        neighbor = next(iter(household.by_role("neighbor")), None)
        return cls(patient=_first(household.patient.name),
                   family=_first(family.name) if family else None,
                   relation=_relation(family.name) if family else None,
                   neighbor=_first(neighbor.name) if neighbor else None)

    @property
    def family_es(self) -> str | None:
        """ "su hija Ana" (or just "Ana")."""
        if self.family and self.relation in _RELATION_ES:
            return f"{_RELATION_ES[self.relation]} {self.family}"
        return self.family

    @property
    def family_en(self) -> str | None:
        """ "her daughter Ana" (or just "Ana")."""
        if self.family and self.relation:
            return f"her {self.relation} {self.family}"
        return self.family


def _first(name: str) -> str:
    return name.split()[0]


def _relation(name: str) -> str | None:
    if "(" in name and name.endswith(")"):
        return name[name.rindex("(") + 1:-1].strip().lower()
    return None


def _ssml(parts: list[str]) -> str:
    body = ""
    for p in parts:
        if p in (BREAK, PAUSE):
            body = body.rstrip() + f'<break time="{"1s" if p == PAUSE else "600ms"}"/>'
        else:
            body += f"{escape(p)} "
    return f'<speak><prosody rate="{SPEECH_RATE}">{body.strip()}</prosody></speak>'


def _call(parts: list[str]) -> Call:
    return Call(" ".join(p for p in parts if p not in (BREAK, PAUSE)), _ssml(parts))


def _sender_es(who: People) -> str:
    return f"de parte de {who.family_es}" if who.family_es else "del aviso de su timbre"


def _helper_es(who: People) -> str:
    if who.neighbor:
        return f"Le vamos a avisar a {who.neighbor} para que le ayude."
    if who.family:
        return f"Le vamos a avisar a {who.family}."
    return "Vamos a pedir ayuda."


# -- the patient, in Spanish ----------------------------------------------------------------


def patient_call_es(purpose: str, who: People, cold: bool) -> Call | None:
    hello = f"Hola, señora {who.patient}. Le llamamos {_sender_es(who)}."
    bye = f"Gracias, señora {who.patient}."
    if purpose == "porch_patient":
        key = "Por favor, métala a la casa y póngala en el refri."
        safe = ("Si hay hielo en el escalón, no salga sola." if cold
                else "Si no puede salir, no se preocupe.")
        return _call([
            hello, BREAK,
            "Su insulina está afuera, en la puerta.", "Hace mucho frío." if cold
            else "Hace mucho calor.", BREAK,
            key, BREAK,
            safe, _helper_es(who), BREAK,
            "No tiene que contestar.", PAUSE,
            f"Repito: su insulina está en la puerta. {key}", BREAK,
            bye,
        ])
    if purpose == "porch_compromised":
        ask = f"Antes de usarla, llame a su farmacia{f' o a {who.family}' if who.family else ''}."
        return _call([
            hello, BREAK,
            f"Su insulina nueva estuvo mucho tiempo afuera, con el {'frío' if cold else 'calor'}.",
            BREAK,
            "No la tire. Guárdela en el refri.", BREAK,
            ask, "Si tiene otra insulina que no estuvo afuera, siga con esa.", BREAK,
            f"{who.family} ya sabe, y le va a conseguir otra." if who.family
            else "Su farmacia le puede dar otra.", PAUSE,
            f"Repito: {ask[0].lower()}{ask[1:]}", BREAK,
            bye,
        ])
    return None


def patient_sms_es(purpose: str, who: People, cold: bool) -> str | None:
    hello = f"Señora {who.patient}, {_sender_es(who)}:"
    if purpose == "porch_patient":
        safe = ("Si hay hielo en el escalón, no salga sola" if cold
                else "Si no puede salir, no se preocupe")
        helper = f": le avisamos a {who.neighbor}." if who.neighbor else "."
        return (f"{hello} su insulina está en la puerta. Hace mucho "
                f"{'frío' if cold else 'calor'}. Métala a la casa y póngala en el refri. "
                f"{safe}{helper} No tiene que contestar.")
    if purpose == "porch_compromised":
        family = f" o a {who.family}" if who.family else ""
        return (f"{hello} su insulina nueva estuvo mucho tiempo afuera con el "
                f"{'frío' if cold else 'calor'}. No la tire: guárdela en el refri. Antes de "
                f"usarla, llame a su farmacia{family}. Si tiene otra insulina que no estuvo "
                f"afuera, siga con esa."
                + (f" {who.family} ya sabe y le va a conseguir otra." if who.family else ""))
    if purpose == "porch_retrieved":
        return (f"Listo, señora {who.patient}: su insulina ya está adentro. Póngala en el "
                f"refri. Gracias.")
    return None


# -- the patient, in English (same rules) -----------------------------------------------------


def _sender_en(who: People) -> str:
    return f"your doorbell alert, set up by {who.family}" if who.family else "your doorbell alert"


def patient_call_en(purpose: str, who: People, cold: bool) -> Call | None:
    hello = f"Hello, {who.patient}. This is {_sender_en(who)}."
    if purpose == "porch_patient":
        key = "Please bring it inside and put it in the fridge."
        safe = ("If the step is icy, don't go out alone." if cold
                else "If you can't go out, don't worry.")
        helper = f"We'll ask {who.neighbor} to help." if who.neighbor else "We'll ask for help."
        return _call([hello, BREAK, "Your medicine is at the front door.",
                      "It's very cold." if cold else "It's very hot.", BREAK, key, BREAK,
                      safe, helper, BREAK, "You don't need to reply.", PAUSE,
                      f"Again: your medicine is at the door. {key}", BREAK, "Thank you."])
    if purpose == "porch_compromised":
        ask = f"Before using it, call your pharmacy{f' or {who.family}' if who.family else ''}."
        return _call([hello, BREAK, "Your new medicine was outside for a long time.", BREAK,
                      "Don't throw it away. Keep it in the fridge.", BREAK, ask,
                      "If you have other medicine that was not outside, keep using that.",
                      PAUSE, f"Again: {ask[0].lower()}{ask[1:]}", BREAK, "Thank you."])
    return None


def patient_sms_en(purpose: str, who: People, cold: bool) -> str | None:
    hello = f"Hi {who.patient}, this is {_sender_en(who)}."
    if purpose == "porch_patient":
        safe = "If the step is icy, don't go out alone" if cold else "If you can't, don't worry"
        helper = f": we'll ask {who.neighbor}." if who.neighbor else "."
        return (f"{hello} Your medicine is at the front door and it's very "
                f"{'cold' if cold else 'hot'}. Please bring it inside and put it in the fridge. "
                f"{safe}{helper} You don't need to reply.")
    if purpose == "porch_compromised":
        family = f" or {who.family}" if who.family else ""
        return (f"{hello} Your new medicine was outside for a long time. Don't throw it away: "
                f"keep it in the fridge. Before using it, call your pharmacy{family}. If you have "
                f"other medicine that was not outside, keep using that.")
    if purpose == "porch_retrieved":
        return f"All set, {who.patient}: your medicine is inside. Put it in the fridge. Thank you."
    return None


def patient_call(purpose: str, who: People, cold: bool, language: str) -> Call | None:
    return (patient_call_es if language == "es" else patient_call_en)(purpose, who, cold)


def patient_sms(purpose: str, who: People, cold: bool, language: str) -> str | None:
    return (patient_sms_es if language == "es" else patient_sms_en)(purpose, who, cold)


# -- the neighbor: what to do, never what is in the box -------------------------------------


def neighbor_sms(who: People, cold: bool, minutes: int, language: str) -> str:
    if language == "es":
        hello = f"Hola, {who.neighbor}." if who.neighbor else "Hola."
        sender = (f"Le escribimos de parte de {who.family}, de la familia de {who.patient}."
                  if who.family else f"Le escribimos del aviso del timbre de {who.patient}.")
        return (f"{hello} {sender} Un paquete para {who.patient} que no debe quedarse afuera "
                f"con el {'frío' if cold else 'calor'} lleva {minutes} min en su puerta. "
                f"¿Podría meterlo a la casa por ella?"
                + (" Cuidado: el escalón puede tener hielo." if cold else ""))
    hello = f"Hi {who.neighbor}" if who.neighbor else "Hi"
    sender = f", set up by {who.family_en}" if who.family else ""
    return (f"{hello}, this is {who.patient}'s doorbell alert{sender}. A delivery for "
            f"{who.patient} that must not stay out in the {'cold' if cold else 'heat'} has been on "
            f"her porch for {minutes} min and she hasn't brought it in. Could you take it inside "
            f"for her?" + (" Careful, the step may be icy." if cold else ""))
