"""Exposure report for a pharmacy replacement claim.

When a temperature-sensitive delivery may have been compromised, the family needs to prove
it to the pharmacy. DoorLedger already holds everything a claim needs: when the parcel was
left (Ring frame), how long it sat outside, the outdoor temperature, the estimated temperature
inside the box, who was notified and when it came inside. This module renders that as a
one-page PDF.
"""

from __future__ import annotations

import io
from datetime import datetime
from pathlib import Path
from zoneinfo import ZoneInfo

from reportlab.lib import colors
from reportlab.lib.pagesizes import LETTER
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import inch
from reportlab.platypus import Image, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from .engine import Engine
from .reconcile import reconcile


def _fmt(dt: datetime | None, tz: ZoneInfo) -> str:
    return dt.astimezone(tz).strftime("%b %d, %Y %I:%M %p") if dt else "—"


def exposure_report(engine: Engine, expectation_id: str, evidence_root: Path) -> bytes:
    exp = engine.expectations.get(expectation_id)
    if exp is None:
        raise KeyError(expectation_id)
    tz = ZoneInfo(engine.household.patient.timezone)
    r = reconcile(list(engine.expectations.values()), engine.observations, engine.clock.now(),
                  engine.ambient, in_sun=engine.household.porch_in_sun)
    d = next(x for x in r.deliveries if x.expectation.id == expectation_id)
    est = d.estimate
    styles = getSampleStyleSheet()
    story = [
        Paragraph("DoorLedger — Medication exposure report", styles["Title"]),
        Paragraph(f"Patient: <b>{engine.household.patient.name}</b>, {engine.household.patient.address}",
                  styles["Normal"]),
        Paragraph(f"Shipment: {exp.title} · carrier {exp.carrier or '—'} · tracking {exp.tracking or '—'}",
                  styles["Normal"]),
        Spacer(1, 0.15 * inch),
    ]
    med = exp.medication
    rows = [
        ["Left at the door (seen by Ring doorbell)", _fmt(d.dropped.at if d.dropped else None, tz)],
        ["Brought inside", _fmt(d.removed.at if d.removed else None, tz)],
        ["Time outside", f"{est.minutes_on_porch:.0f} min" if est else "—"],
        ["Outdoor temperature", f"{est.ambient_c:.0f} °C" if est else "—"],
        ["Estimated temperature inside the box", f"{est.estimated_internal_c} °C" if est else "—"],
        ["Required storage", f"{med.store_min_c:.0f}–{med.store_max_c:.0f} °C; never frozen; "
                             f"never above {med.excursion_max_c:.0f} °C" if med else "—"],
        ["DoorLedger assessment", (est.status.replace("_", " ") if est else "—")],
    ]
    table = Table(rows, colWidths=[2.9 * inch, 3.6 * inch])
    table.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.4, colors.grey),
        ("BACKGROUND", (0, 0), (0, -1), colors.whitesmoke),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
    ]))
    story += [table, Spacer(1, 0.2 * inch)]

    for label, obs in (("Parcel left", d.dropped), ("Parcel taken inside", d.removed)):
        if obs and obs.evidence_path:
            path = evidence_root / obs.evidence_path.removeprefix("evidence/")
            if path.is_file():
                story += [Paragraph(f"{label} — {_fmt(obs.at, tz)} — source: {obs.source}",
                                    styles["Italic"]),
                          Image(str(path), width=4.8 * inch, height=2.7 * inch),
                          Spacer(1, 0.1 * inch)]

    actions = [rec["body"] for rec in engine.ledger.records(kinds=["action"])
               if rec["ref"] == expectation_id or rec["body"].get("finding_id")]
    if actions:
        story.append(Paragraph("Who was notified", styles["Heading3"]))
        for a in actions:
            when = datetime.fromisoformat(a["at"])
            story.append(Paragraph(f"{_fmt(when, tz)} — {a['kind']} → {a['target']}", styles["Normal"]))
    story += [
        Spacer(1, 0.2 * inch),
        Paragraph("The inside-the-box temperature is an estimate from a documented thermal model "
                  "(Newton's law of cooling, insulated mailer), not a measurement. Camera frames are "
                  "stored with faces pixelated. Generated by DoorLedger.", styles["Italic"]),
    ]
    buf = io.BytesIO()
    SimpleDocTemplate(buf, pagesize=LETTER, title="Medication exposure report").build(story)
    return buf.getvalue()
